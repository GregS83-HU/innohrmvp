CREATE OR REPLACE FUNCTION public.check_overlapping_leaves(user_id_param uuid, year_param integer)
 RETURNS json
 LANGUAGE plpgsql
AS $function$
DECLARE
    result JSON;
BEGIN
    SELECT COALESCE(json_agg(
        json_build_object(
            'date', overlap_date,
            'request_ids', request_ids
        )
    ), '[]'::json) INTO result
    FROM (
        SELECT 
            date_series.date AS overlap_date,
            array_agg(DISTINCT lr.id) AS request_ids
        FROM leave_requests lr
        CROSS JOIN LATERAL generate_series(
            lr.start_date,
            lr.end_date,
            '1 day'::interval
        ) AS date_series(date)
        WHERE lr.user_id = user_id_param
        AND EXTRACT(YEAR FROM date_series.date) = year_param
        AND lr.status IN ('approved', 'pending')
        GROUP BY date_series.date
        HAVING COUNT(DISTINCT lr.id) > 1
    ) AS overlap_data;
    
    RETURN result;
END;
$function$
;

