CREATE OR REPLACE FUNCTION public.sync_leave_to_attendance()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  day_date DATE;
BEGIN
  IF NEW.status = 'approved' AND (OLD.status IS NULL OR OLD.status != 'approved') THEN
    -- Generate exception for each day in the leave period
    FOR day_date IN 
      SELECT generate_series(
        NEW.start_date::DATE,
        NEW.end_date::DATE,
        '1 day'::INTERVAL
      )::DATE
    LOOP
      INSERT INTO attendance_exceptions (
        user_id, 
        exception_date, 
        exception_type, 
        leave_request_id
      )
      VALUES (
        NEW.user_id, 
        day_date, 
        'approved_absence', 
        NEW.id
      )
      ON CONFLICT (user_id, exception_date) DO NOTHING;
    END LOOP;
  END IF;
  
  RETURN NEW;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.update_daily_happiness_metrics(target_date date)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
BEGIN
    INSERT INTO happiness_daily_metrics (
        metric_date,
        total_sessions_started,
        total_sessions_completed,
        completion_rate,
        avg_overall_happiness,
        avg_positive_emotions,
        avg_engagement,
        avg_relationships,
        avg_meaning,
        avg_accomplishment,
        avg_work_life_balance
    )
    SELECT 
        target_date,
        COUNT(*) as total_started,
        COUNT(*) FILTER (WHERE status = 'completed') as total_completed,
        ROUND(
            (COUNT(*) FILTER (WHERE status = 'completed')::DECIMAL / NULLIF(COUNT(*), 0)) * 100, 
            2
