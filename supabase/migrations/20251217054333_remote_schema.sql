CREATE OR REPLACE FUNCTION public.update_leave_balances()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE leave_balances 
        SET 
            pending_days = pending_days + NEW.total_days,
            updated_at = NOW()
        WHERE 
            user_id = NEW.user_id 
            AND leave_type_id = NEW.leave_type_id 
            AND year = EXTRACT(YEAR FROM NEW.start_date);
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.status = 'pending' AND NEW.status = 'approved' THEN
            UPDATE leave_balances 
            SET 
                pending_days = pending_days - NEW.total_days,
                used_days = used_days + NEW.total_days,
                updated_at = NOW()
            WHERE 
                user_id = NEW.user_id 
                AND leave_type_id = NEW.leave_type_id 
                AND year = EXTRACT(YEAR FROM NEW.start_date);
        END IF;

        IF OLD.status = 'pending' AND NEW.status IN ('rejected', 'cancelled') THEN
            UPDATE leave_balances 
            SET 
                pending_days = pending_days - NEW.total_days,
                updated_at = NOW()
            WHERE 
                user_id = NEW.user_id 
                AND leave_type_id = NEW.leave_type_id 
                AND year = EXTRACT(YEAR FROM NEW.start_date);
        END IF;

        IF OLD.status = 'approved' AND NEW.status = 'cancelled' THEN
            UPDATE leave_balances 
            SET 
                used_days = used_days - NEW.total_days,
                updated_at = NOW()
            WHERE 
                user_id = NEW.user_id 
                AND leave_type_id = NEW.leave_type_id 
                AND year = EXTRACT(YEAR FROM NEW.start_date);
        END IF;

        RETURN NEW;
    END IF;

    IF TG_OP = 'DELETE' THEN
        IF OLD.status = 'pending' THEN
            UPDATE leave_balances 
            SET 
                pending_days = pending_days - OLD.total_days,
                updated_at = NOW()
            WHERE 
                user_id = OLD.user_id 
                AND leave_type_id = OLD.leave_type_id 
                AND year = EXTRACT(YEAR FROM OLD.start_date);
        ELSIF OLD.status = 'approved' THEN
            UPDATE leave_balances 
            SET 
                used_days = used_days - OLD.total_days,
                updated_at = NOW()
            WHERE 
                user_id = OLD.user_id 
                AND leave_type_id = OLD.leave_type_id 
                AND year = EXTRACT(YEAR FROM OLD.start_date);
        END IF;
        RETURN OLD;
    END IF;

    RETURN NULL;
END;
$function$
;

