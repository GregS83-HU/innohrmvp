CREATE OR REPLACE FUNCTION public.check_certificate_date_alignment(leave_request_id_param uuid)
 RETURNS json
 LANGUAGE plpgsql
AS $function$
DECLARE
    result JSON;
    cert_record RECORD;
    leave_record RECORD;
